"""Statistical validation on the realistic population: v2 must dominate v1 (paper §V-C).

The realistic dataset (fixtures/eval_realistic/, generated by scripts/gen_realistic_eval.py from
Alibaba-like topology distributions, fixed seed) injects one Sub-SLO fault per scenario on a
low-centrality service — the regime where uniform decomposition under-allocates. This test locks
the headline: weighted decomposition (v2) detects the vast majority while uniform (v1) detects a
small minority, with a wide, stable margin. It exercises only the public run_eval harness.
"""

from __future__ import annotations

from pathlib import Path

from slacheck.eval.runner import run_eval

REPO = Path(__file__).resolve().parents[1]
DATASET = REPO / "fixtures" / "eval_realistic"


def test_dataset_present_and_sized():
    scenarios = list((DATASET / "sub_slo").glob("*.yaml"))
    assert len(scenarios) >= 100  # a population, not a handful


def test_v2_dominates_v1_on_realistic_population():
    v1 = run_eval(DATASET, "v1")
    v2 = run_eval(DATASET, "v2")
    n = v2.injected("sub_slo")
    d1, d2 = v1.detected("sub_slo"), v2.detected("sub_slo")
    assert n >= 100
    # v2 detects the large majority; v1 only a small minority — a wide, structural margin.
    assert d2 / n > 0.80
    assert d1 / n < 0.20
    assert d2 > 4 * d1
